// Preserve generator classes when an app rebuilds CSS before generating its
// next scaffold/auth page. Tailwind scans the resulting plain-text manifest.
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../src/azu_cli/templates');
const classes = new Set();
function visit(directory) {
  for (const entry of readdirSync(directory, {withFileTypes: true})) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) visit(path);
    else if (entry.name.endsWith('.ecr')) {
      for (const match of readFileSync(path, 'utf8').matchAll(/class(?:=|:\s*)"([^"]*)"/g)) {
        for (const token of match[1].split(/\s+/)) {
          if (/^[a-zA-Z0-9_\[!][a-zA-Z0-9_/.:\[\]()%#,!>\-]*$/.test(token)) classes.add(token);
        }
      }
    }
  }
}
visit(join(root, 'scaffold/public/templates'));
visit(join(root, 'auth/public/templates'));
visit(join(root, 'spark_component'));
visit(join(root, 'spark_scaffold'));
writeFileSync(join(root, 'project/frontend/generator-classes.txt'),
  '# Generated by scripts/frontend_classes.mjs. Keep to style future scaffolds/auth pages.\n' +
  [...classes].sort().join('\n') + '\n');
